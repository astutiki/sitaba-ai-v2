@router.delete("/{filename}")
def delete_export(filename: str):

    filepath = os.path.join(
        EXPORT_FOLDER,
        filename
    )

    if not os.path.exists(filepath):

        raise HTTPException(
            status_code=404,
            detail="File tidak ditemukan."
        )

    os.remove(filepath)

    return {

        "success": True,

        "message": "File berhasil dihapus."

    }