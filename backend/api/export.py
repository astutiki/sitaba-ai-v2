def export_word(question, answer):

    filename = f"chat_{datetime.now().strftime('%Y%m%d_%H%M%S')}.docx"
    filepath = os.path.join(EXPORT_FOLDER, filename)

    doc = Document()

    title = doc.add_heading("AI SINTA", level=1)
    title.alignment = WD_PARAGRAPH_ALIGNMENT.CENTER

    subtitle = doc.add_paragraph("Asisten Informasi Kebencanaan SITABA")
    subtitle.alignment = WD_PARAGRAPH_ALIGNMENT.CENTER

    doc.add_paragraph()

    doc.add_heading("Pertanyaan", level=2)
    p = doc.add_paragraph()
    run = p.add_run(question)
    run.font.size = Pt(10)

    doc.add_paragraph()

    doc.add_heading("Jawaban AI", level=2)

    for line in answer.split("\n"):
        line = line.strip()

        if not line:
            continue

        if line.startswith("•"):
            p = doc.add_paragraph(style="List Bullet")
            p.add_run(line.replace("•", "").strip())
        else:
            p = doc.add_paragraph()
            run = p.add_run(line)
            run.font.size = Pt(10)

    doc.add_paragraph()

    footer = doc.add_paragraph()
    footer.alignment = WD_PARAGRAPH_ALIGNMENT.CENTER
    run = footer.add_run(
        "Generated by AI SINTA - Kementerian PU | "
        + datetime.now().strftime("%d-%m-%Y %H:%M:%S")
    )
    run.italic = True
    run.font.size = Pt(9)

    doc.save(filepath)

    return filepath


