@router.get("/download/{filename}")
def download_file(filename: str):

    filepath = os.path.join(
        EXPORT_FOLDER,
        filename
    )

    if not os.path.exists(filepath):

        raise HTTPException(
            status_code=404,
            detail="File tidak ditemukan."
        )

    return FileResponse(
        filepath,
        filename=filename
    )


# =====================================================
# LIST FILE
# =====================================================

@router.get("/files")
def list_export():

    files = []

    for file in os.listdir(EXPORT_FOLDER):

        files.append({

            "filename": file,

            "download": f"/export/download/{file}"

        })

    return {

        "success": True,

        "total": len(files),

        "files": files

    }


