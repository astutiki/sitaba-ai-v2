def export_txt(question, answer):

    filename = f"chat_{datetime.now().strftime('%Y%m%d_%H%M%S')}.txt"
    filepath = os.path.join(EXPORT_FOLDER, filename)

    created_at = datetime.now().strftime("%d-%m-%Y %H:%M:%S")

    with open(filepath, "w", encoding="utf-8") as f:
        f.write("AI SINTA - LAPORAN HASIL CHAT\n")
        f.write("=" * 60)
        f.write("\n\n")

        f.write("PERTANYAAN\n")
        f.write("-" * 60)
        f.write("\n")
        f.write(question.strip())
        f.write("\n\n")

        f.write("JAWABAN\n")
        f.write("-" * 60)
        f.write("\n")

        for line in answer.split("\n"):
            line = line.strip()
            if line:
                f.write(line + "\n")
            else:
                f.write("\n")

        f.write("\n")
        f.write("=" * 60)
        f.write("\n")
        f.write(f"Generated by AI SINTA - Kementerian PU\n")
        f.write(f"Tanggal Export: {created_at}\n")

    return filepath


