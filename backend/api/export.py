def export_excel(question, answer):

    filename = f"chat_{datetime.now().strftime('%Y%m%d_%H%M%S')}.xlsx"
    filepath = os.path.join(EXPORT_FOLDER, filename)

    wb = Workbook()
    ws = wb.active
    ws.title = "AI SINTA"

    blue_fill = PatternFill("solid", fgColor="1F4E78")
    light_fill = PatternFill("solid", fgColor="D9EAF7")
    white_font = Font(color="FFFFFF", bold=True)
    bold_font = Font(bold=True)
    thin = Side(border_style="thin", color="D9D9D9")
    border = Border(left=thin, right=thin, top=thin, bottom=thin)

    ws.merge_cells("A1:D1")
    ws["A1"] = "LAPORAN AI SINTA"
    ws["A1"].font = Font(size=16, bold=True, color="FFFFFF")
    ws["A1"].fill = blue_fill
    ws["A1"].alignment = Alignment(horizontal="center")

    ws["A3"] = "Pertanyaan"
    ws["B3"] = question
    ws["A4"] = "Tanggal Export"
    ws["B4"] = datetime.now().strftime("%d-%m-%Y %H:%M:%S")

    for cell in ["A3", "A4"]:
        ws[cell].font = bold_font
        ws[cell].fill = light_fill

    headers = ["No", "Kategori", "Isi Jawaban", "Keterangan"]
    ws.append([])
    ws.append(headers)

    header_row = 6

    for col in range(1, 5):
        cell = ws.cell(row=header_row, column=col)
        cell.font = white_font
        cell.fill = blue_fill
        cell.alignment = Alignment(horizontal="center")
        cell.border = border

    lines = [line.strip() for line in answer.split("\n") if line.strip()]

    row = 7
    no = 1

    for line in lines:
        kategori = "Isi"

        if line.startswith("📍"):
            kategori = "Judul"
        elif line.startswith("📌") or line.startswith("🗺") or line.startswith("🏙") or line.startswith("🚧") or line.startswith("🏚") or line.startswith("🛣") or line.startswith("📋"):
            kategori = "Bagian"
        elif line.startswith("•"):
            kategori = "Poin"
        elif line[:2].replace(".", "").isdigit():
            kategori = "Detail"

        ws.cell(row=row, column=1, value=no)
        ws.cell(row=row, column=2, value=kategori)
        ws.cell(row=row, column=3, value=line)
        ws.cell(row=row, column=4, value="")

        for col in range(1, 5):
            cell = ws.cell(row=row, column=col)
            cell.border = border
            cell.alignment = Alignment(vertical="top", wrap_text=True)

        if kategori in ["Judul", "Bagian"]:
            for col in range(1, 5):
                ws.cell(row=row, column=col).fill = light_fill
                ws.cell(row=row, column=col).font = bold_font

        row += 1
        no += 1

    ws.column_dimensions["A"].width = 8
    ws.column_dimensions["B"].width = 18
    ws.column_dimensions["C"].width = 90
    ws.column_dimensions["D"].width = 25

    ws.freeze_panes = "A7"
    ws.auto_filter.ref = f"A6:D{row-1}"

    wb.save(filepath)

    return filepath


