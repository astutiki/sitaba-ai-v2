@router.post("/")
def export_chat(data: ExportRequest):

    format = data.format.lower()

    if format == "pdf":

        path = export_pdf(
            data.question,
            data.answer
        )

    elif format == "docx":

        path = export_word(
            data.question,
            data.answer
        )

    elif format == "xlsx":

        path = export_excel(
            data.question,
            data.answer
        )

    elif format == "csv":

        path = export_csv(
            data.question,
            data.answer
        )

    elif format == "txt":

        path = export_txt(
            data.question,
            data.answer
        )

    elif format == "json":

        path = export_json(
            data.question,
            data.answer
        )

    else:

        raise HTTPException(
            status_code=400,
            detail="Format export tidak didukung."
        )

    return {

        "success": True,

        "message": "Export berhasil.",

        "file": os.path.basename(path),

        "download": f"/export/download/{os.path.basename(path)}"

    }


